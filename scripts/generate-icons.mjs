/**
 * Converts design/icons/*.svg (exported from Figma) into components/icons/*.tsx.
 * Black, white and the design's red (trash, drawn in the non-AA #ff0000; D-004) become
 * currentColor so callers colour them with tokens; the brand lime becomes var(--brand).
 *
 * Usage: node scripts/generate-icons.mjs [--check]
 */
import fs from 'node:fs';
import path from 'node:path';

const SRC = 'design/icons';
const OUT = 'components/icons';
const icons = JSON.parse(fs.readFileSync('design/spec/icons.json', 'utf8')).icons;

/**
 * Converts kebab-case SVG attributes to React props.
 * @param {string} svg SVG markup.
 * @returns {string} JSX-compatible markup.
 */
function toJsx(svg) {
  return svg
    .replace(/\s(fill|stroke)="(white|#fff|#ffffff|black|#000|#000000|#ff0000)"/gi, ' $1="currentColor"')
    .replace(/\s(fill|stroke)="#c7f126"/gi, ' $1="var(--brand)"')
    .replace(/([a-z])-([a-z])(?=[a-z-]*=)/g, (_, a, b) => `${a}${b.toUpperCase()}`)
    .replace(/xlink:href/g, 'href')
    .replace(/\sxmlns(:\w+)?="[^"]*"/g, '');
}

const stale = [];
fs.mkdirSync(OUT, { recursive: true });
const exportsList = [];
for (const icon of icons) {
  const svg = fs.readFileSync(path.join(SRC, `${icon.figma}.svg`), 'utf8').trim();
  const [, width, height] = /width="([\d.]+)" height="([\d.]+)"/.exec(svg);
  const body = toJsx(svg)
    .replace(/^<svg[^>]*>/, '')
    .replace(/<\/svg>$/, '')
    .trim();
  const viewBox = /viewBox="([^"]+)"/.exec(svg)[1];
  const file = `// GENERATED by scripts/generate-icons.mjs from design/icons/${icon.figma}.svg — do not edit.
import type { SVGProps } from 'react';

/** "${icon.figma}" from the Figma file, drawn at ${width}×${height}. */
export function ${icon.component}(props: SVGProps<SVGSVGElement>) {
  return (
    <svg width={${width}} height={${height}} viewBox="${viewBox}" fill="none" aria-hidden="true" focusable="false" {...props}>
      ${body.split('\n').join('\n      ')}
    </svg>
  );
}
`;
  const target = path.join(OUT, `${icon.figma}.tsx`);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== file) stale.push(target);
  } else fs.writeFileSync(target, file);
  exportsList.push(`export { ${icon.component} } from './${icon.figma}';`);
}
const index = `// GENERATED by scripts/generate-icons.mjs — do not edit.\n${exportsList.join('\n')}\n`;
if (process.argv.includes('--check')) {
  if (fs.readFileSync(path.join(OUT, 'index.ts'), 'utf8') !== index) stale.push('index.ts');
  if (stale.length) {
    console.error(`FAIL stale icons: ${stale.join(', ')}`);
    process.exit(1);
  }
  console.log('✓ icons in sync');
} else {
  fs.writeFileSync(path.join(OUT, 'index.ts'), index);
  console.log(`wrote ${icons.length} icons`);
}
