/**
 * Generates styles/tokens.generated.css from docs/app/design-tokens.json (the derived tokens —
 * the Figma file has no variables) and checks the configured contrast pairs (WCAG AA).
 *
 * Usage: node scripts/generate-theme.mjs [--check]
 *   --check  fail if the committed CSS is stale or a contrast pair fails.
 */
import fs from 'node:fs';

const SOURCE = 'docs/app/design-tokens.json';
const OUT = 'styles/tokens.generated.css';
const tokens = JSON.parse(fs.readFileSync(SOURCE, 'utf8'));

/** Font sizes used by the design, in px (design/spec/outline). */
const TEXT_SIZES = [14, 16, 17, 18, 20, 22, 24, 25, 26, 28, 30, 32, 34, 40, 44, 48, 50, 54, 56, 60, 68, 100, 120, 150];
/**
 * Sizes inside groups the design scales (Size Guide help strip, ×1.0556), named for their role,
 * plus the bag-count badge (derived: the design shows no count; 11 px fits two digits in 16 px).
 */
const NAMED_TEXT_SIZES = { 'callout-title': 33.78, 'callout-body': 27.44, 'callout-label': 23.22, 'callout-small': 21.11, badge: 11 };
/** Inter's (ascender + |descender|) / unitsPerEm — what Figma renders for line height "auto". */
const AUTO_LEADING = 1.2102;
/** Stacking layers: sticky header (and its mega panels), dialogs and drawers, toasts. */
const Z_LAYERS = { nav: 40, overlay: 50, toast: 60 };

/**
 * Relative luminance of a hex colour (WCAG 2.x).
 * @param {string} hex `#rrggbb`.
 * @returns {number} Luminance 0–1.
 */
function luminance(hex) {
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255);
  const lin = (c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
  return 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b);
}

/**
 * Contrast ratio between two hex colours.
 * @param {string} a Foreground.
 * @param {string} b Background.
 * @returns {number} Ratio ≥ 1.
 */
function contrast(a, b) {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
}

const px = (n) => `${n}px`;
const lines = [
  '/* GENERATED by scripts/generate-theme.mjs from docs/app/design-tokens.json — do not edit. */',
  '',
  ':root {',
  ...Object.entries(tokens.colors).map(([name, { value }]) => `  --${name}: ${value};`),
  '}',
  '',
  '/* The design has no dark frames; dark mode keeps the light values (docs/app/design-decisions.md D-003). */',
  '.dark {',
  ...Object.keys(tokens.colors).map((name) => `  --${name}: ${tokens.colors[name].value};`),
  '}',
  '',
  '@theme inline {',
  ...Object.keys(tokens.colors).map((name) => `  --color-${name}: var(--${name});`),
  ...Object.entries(tokens.radius).map(([name, value]) => `  --radius-${name}: ${px(value)};`),
  `  --font-sans: var(--font-inter), ui-sans-serif, system-ui, sans-serif;`,
  `  --font-display: var(--font-montserrat), var(--font-inter), ui-sans-serif, sans-serif;`,
  // Figma's "auto" line height is the font's ascent + descent (Inter: 1.2102 em), rounded to whole px.
  ...[...TEXT_SIZES.map((size) => [size, size]), ...Object.entries(NAMED_TEXT_SIZES)].flatMap(([name, size]) => [
    `  --text-${name}: ${px(size)};`,
    `  --text-${name}--line-height: ${px(Math.round(size * AUTO_LEADING))};`,
  ]),
  '  --tracking-tight-3: -0.03em;',
  '  --tracking-tight-2: -0.02em;',
  '  --tracking-tight-1: -0.01em;',
  '  --tracking-wide-2: 0.02em;',
  ...Object.entries(tokens.shadows).map(([name, value]) => `  --shadow-${name}: ${value};`),
  ...Object.entries(tokens.breakpoints).map(([name, value]) => `  --breakpoint-${name}: ${value};`),
  ...Object.entries(tokens.layout).map(([name, value]) => `  --${name}: ${value};`),
  ...Object.entries(Z_LAYERS).map(([name, value]) => `  --z-${name}: ${value};`),
  '}',
  '',
  // Tailwind v4 has no z-index theme namespace, so each layer is its own utility (BUG-005).
  ...Object.keys(Z_LAYERS).flatMap((name) => [`@utility z-${name} {`, `  z-index: var(--z-${name});`, '}', '']),
];
const css = lines.join('\n');

const failures = [];
for (const [fg, bg, size] of tokens.contrast) {
  const ratio = contrast(tokens.colors[fg].value, tokens.colors[bg].value);
  const min = size === 'large' ? 3 : 4.5;
  if (ratio < min) failures.push(`${fg} on ${bg}: ${ratio.toFixed(2)} < ${min}`);
}

if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
  if (current !== css) failures.push(`${OUT} is stale — run node scripts/generate-theme.mjs`);
  if (failures.length) {
    for (const f of failures) console.error(`FAIL ${f}`);
    process.exit(1);
  }
  console.log('✓ theme in sync, contrast pairs pass');
} else {
  fs.mkdirSync('styles', { recursive: true });
  fs.writeFileSync(OUT, css);
  console.log(`wrote ${OUT}`);
  for (const f of failures) console.error(`FAIL ${f}`);
  if (failures.length) process.exit(1);
}
